/**
 * Узел дерева прав.
 * Может быть:
 *  - PermissionNode — лист (конкретное разрешение)
 *  - RoleNode — композит (роль, содержащая другие узлы)
 *
 * Обход дерева идёт сверху вниз, рекурсивно.
 * Наследование: роль наследует все разрешения своих детей.
 */
export interface RbacNode {
  /** Имя узла (роль или разрешение) */
  name: string;

  /** Тип узла: 'role' — композит, 'permission' — лист */
  kind: 'role' | 'permission';

  /** Дочерние узлы (только у роли) */
  children?: RbacNode[];

  /**
   * Проверить, содержит ли узел (или кто-то из его детей)
   * указанное разрешение.
   */
  hasPermission(permission: string): boolean;

  /**
   * Собрать все разрешения в поддереве.
   */
  getAllPermissions(): string[];
}
